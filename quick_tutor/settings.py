def _load_dotenv(path):
    """Read a .env file into os.environ.

    A real environment variable always wins, so a deployment can override the
    file without editing it. Kept deliberately small — the project has no
    dependency on python-dotenv, and this covers what a .env actually needs:
    comments, blank lines, an optional `export ` prefix, and quoted values.
    """
    if not path.exists():
        return
    for raw in path.read_text(encoding='utf-8').splitlines():
        line = raw.strip()
        if not line or line.startswith('#') or '=' not in line:
            continue
        if line.startswith('export '):
            line = line[len('export '):]
        key, _, value = line.partition('=')
        key, value = key.strip(), value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in ('"', "'"):
            value = value[1:-1]
        os.environ.setdefault(key, value)


_load_dotenv(BASE_DIR / '.env')


